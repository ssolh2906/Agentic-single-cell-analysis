# Save a reference to the real generator method
original_generate = ChatAnthropic._generate


def patched_generate(self, messages, *args, **kwargs):
    if isinstance(messages, list) and len(messages) > 0:
        # Forcefully strip ANY message that causes a trailing assistant state
        # directly modifying a copy so we don't break the original LangGraph state
        messages = list(messages)

        while messages and isinstance(messages[-1], AIMessage):
            messages.pop()

        # Optional Safeguard: If it still leaves the state dangling or empty,
        # ensure it finishes cleanly with a tiny human acknowledgment.
        if len(messages) == 0:
            messages.append(HumanMessage(content="Please proceed."))

    return original_generate(self, messages, *args, **kwargs)


ChatAnthropic._generate = patched_generate
# -------------------------------------------------
# Overwrite the class level method so every instance gets the fix
ChatAnthropic._generate = patched_generate

