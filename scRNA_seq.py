# Intercept the underlying language model's invoke/generate method
# Get the true underlying LLM object bypassing the Pydantic wrapper
# Depending on the LangChain wrapper version, it's either agent.llm.bound or agent.llm
from langchain_anthropic import ChatAnthropic
from langchain_core.messages import AIMessage, HumanMessage

